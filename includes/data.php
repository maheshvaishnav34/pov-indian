function pov_location_match_terms(string $slug): array {
  $map = [
    'delhi-ncr' => ['delhi', 'ncr'],
    'mumbai' => ['mumbai'],
    'bangalore' => ['bangalore', 'bengaluru'],
    'kolkata' => ['kolkata'],
    'chennai' => ['chennai'],
    'jaipur' => ['jaipur'],
    'hyderabad' => ['hyderabad'],
    'pune' => ['pune'],
    'kochi' => ['kochi'],
    'udaipur' => ['udaipur'],
    'goa' => ['goa'],
    'ahmedabad' => ['ahmedabad'],
  ];
  return $map[$slug] ?? [str_replace('-', ' ', $slug)];
}

function pov_listings_by_location(?string $slug): array {
  global $POV_LISTINGS;
  if ($slug === null || $slug === '') {
    return $POV_LISTINGS;
  }
  $terms = pov_location_match_terms($slug);
  return array_values(array_filter($POV_LISTINGS, function ($item) use ($terms) {
    $hay = strtolower((string)($item['loc'] ?? ''));
    foreach ($terms as $term) {
      $term = strtolower((string)$term);
      if ($term !== '' && str_contains($hay, $term)) {
        return true;
      }
    }
    return false;
  }));
}

