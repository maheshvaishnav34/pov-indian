function pov_related_listings(array $item, int $limit = 3): array {
  $same = array_values(array_filter(
    pov_listings_by_category((string)($item['cat_slug'] ?? '')),
    fn($row) => (int)$row['id'] !== (int)$item['id']
  ));
  if (count($same) >= $limit) {
    return array_slice($same, 0, $limit);
  }
  global $POV_LISTINGS;
  $extra = array_values(array_filter(
    $POV_LISTINGS,
    fn($row) => (int)$row['id'] !== (int)$item['id'] && !in_array($row['id'], array_column($same, 'id'), true)
  ));
  return array_slice(array_merge($same, $extra), 0, $limit);
}

