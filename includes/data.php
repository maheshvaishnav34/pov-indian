/**
 * Check if a category matches a user interest key/slug/name.
 */
function pov_category_matches_interest(array $cat, string $interest): bool {
  $cleanInterest = trim($interest);
  if ($cleanInterest === '') {
    return false;
  }

  $catSlug = trim((string)($cat['slug'] ?? ''));
  $catName = trim((string)($cat['name'] ?? ''));

  // 1. Direct match on slug or name
  if (strcasecmp($catSlug, $cleanInterest) === 0 || strcasecmp($catName, $cleanInterest) === 0) {
    return true;
  }

  // 2. Normalized alphanumeric match
  $normInterest = strtolower((string)preg_replace('/[^a-z0-9]/i', '', $cleanInterest));
  $normSlug = strtolower((string)preg_replace('/[^a-z0-9]/i', '', $catSlug));
  $normName = strtolower((string)preg_replace('/[^a-z0-9]/i', '', $catName));

  if ($normInterest === '' || $normSlug === '') {
    return false;
  }

  if ($normInterest === $normSlug || $normInterest === $normName) {
    return true;
  }

  // 3. Substring match (e.g. 'hotels' in 'hotelsaccommodations')
  if (strlen($normInterest) >= 4 && (str_contains($normName, $normInterest) || str_contains($normInterest, $normSlug))) {
    return true;
  }
  if (strlen($normSlug) >= 4 && str_contains($normInterest, $normSlug)) {
    return true;
  }

  return false;
}

/**
 * Retrieve current logged-in user's interests as a normalized array of strings.
 */
function pov_get_current_user_interests(): array {
  if (session_status() === PHP_SESSION_NONE) {
    @session_start();
  }
  $user = $_SESSION['auth_user'] ?? $_SESSION['user'] ?? null;
  if (!$user) {
    return [];
  }

  $raw = $user['interests'] ?? [];
  if (is_string($raw)) {
    $raw = preg_split('/[,;\n]+/', $raw);
  }
  if (!is_array($raw)) {
    return [];
  }

  $clean = [];
  foreach ($raw as $item) {
    $str = trim((string)$item);
    if ($str !== '' && !in_array($str, $clean, true)) {
      $clean[] = $str;
    }
  }
  return $clean;
}

/**
 * Check if the active session has personalization active.
 */
function pov_is_user_personalized(): bool {
  if (session_status() === PHP_SESSION_NONE) {
    @session_start();
  }
  $user = $_SESSION['auth_user'] ?? $_SESSION['user'] ?? null;
  if (!$user) {
    return false;
  }
  $interests = pov_get_current_user_interests();
  return !empty($interests);
}

/**
 * Get categories allowed for the current visitor.
 * For guests or users without interests, returns ALL categories.
 * For logged-in users with interests, returns ONLY matching categories.
 */
function pov_get_user_allowed_categories(): array {
  global $POV_CATEGORIES;
  $allCats = is_array($POV_CATEGORIES) ? $POV_CATEGORIES : [];

  if (!pov_is_user_personalized()) {
    return $allCats;
  }

  $interests = pov_get_current_user_interests();
  if (empty($interests)) {
    return $allCats;
  }

  $matched = [];
  foreach ($allCats as $cat) {
    foreach ($interests as $interest) {
      if (pov_category_matches_interest($cat, $interest)) {
        $matched[] = $cat;
        break;
      }
    }
  }

  // If no categories match (e.g. obsolete custom tag), fallback safely to all
  return !empty($matched) ? $matched : $allCats;
}

/**
 * Get listings allowed for the current visitor.
 * Returns only listings belonging to user's allowed categories.
 */
function pov_get_user_allowed_listings(): array {
  global $POV_LISTINGS;
  $allListings = is_array($POV_LISTINGS) ? $POV_LISTINGS : [];

  if (!pov_is_user_personalized()) {
    return $allListings;
  }

  $allowedCats = pov_get_user_allowed_categories();
  $matchedListings = [];

  foreach ($allListings as $item) {
    $itemSlug = trim((string)($item['cat_slug'] ?? ''));
    $itemName = trim((string)($item['cat'] ?? ''));
    $isMatch = false;

    foreach ($allowedCats as $cat) {
      if (pov_category_matches_interest($cat, $itemSlug) || pov_category_matches_interest($cat, $itemName)) {
        $isMatch = true;
        break;
      }
    }

    if ($isMatch) {
      $matchedListings[] = $item;
    }
  }

  return $matchedListings;
}


