/**
 * Normalize any rental item ensuring all required keys exist and avoiding PHP notices
 */
function pov_normalize_rental_item(array $item): array {
  $img = !empty($item['img']) ? $item['img'] : (!empty($item['image']) ? $item['image'] : 'realestate_01.webp');
  $item['img'] = $img;
  $item['image'] = $img;

  $title = trim((string)($item['title'] ?? 'Rental Property'));
  $item['title'] = $title;

  $desc = !empty($item['desc']) ? $item['desc'] : (!empty($item['description']) ? $item['description'] : ($title . ' - verified accommodation with comfortable amenities.'));
  $item['desc'] = $desc;
  $item['description'] = $desc;

  $hostName = !empty($item['host_name']) ? $item['host_name'] : (!empty($item['provider_name']) ? $item['provider_name'] : 'Verified Host');
  $item['host_name'] = $hostName;
  $item['provider_name'] = $hostName;

  $hostPhone = !empty($item['host_phone']) ? $item['host_phone'] : (!empty($item['phone']) ? $item['phone'] : '+91 98765 43210');
  $item['host_phone'] = $hostPhone;
  $item['phone'] = $hostPhone;

  $item['provider_type'] = !empty($item['provider_type']) ? $item['provider_type'] : 'Direct Owner';

  // Landmark & Locality handling (eliminates empty ", Abu road")
  $city = trim((string)($item['city'] ?? 'India'));
  $item['city'] = $city ?: 'India';
  $item['state'] = trim((string)($item['state'] ?? ''));

  $lm = trim((string)($item['landmark'] ?? ''));
  $loc = trim((string)($item['locality'] ?? ''));
  if ($loc === '' && $lm !== '') $loc = $lm;
  if ($lm === '' && $loc !== '') $lm = $loc;
  if ($lm === '' && $loc === '') {
    $lm = $city;
    $loc = $city;
  }
  $item['landmark'] = $lm;
  $item['locality'] = $loc;

  $dist = trim((string)($item['landmark_distance'] ?? ''));
  $item['landmark_distance'] = $dist;

  // Pricing
  $item['price'] = trim((string)($item['price'] ?? '₹12,000'));
  $item['price_unit'] = trim((string)($item['price_unit'] ?? '/ month'));
  $item['deposit'] = trim((string)($item['deposit'] ?? '₹20,000'));
  $item['maintenance'] = trim((string)($item['maintenance'] ?? 'Included in rent'));
  $item['move_in_est'] = trim((string)($item['move_in_est'] ?? ($item['price'] . ' (1st mo) + ' . $item['deposit'])));
  $item['price_num'] = !empty($item['numeric_price']) ? (int)$item['numeric_price'] : (int)preg_replace('/[^0-9]/', '', $item['price']);

  // Lifestyle & Specs
  $bhk = !empty($item['bhk']) ? $item['bhk'] : '1 BHK';
  $item['bhk'] = $bhk;
  $item['occupancy'] = !empty($item['occupancy']) ? $item['occupancy'] : $bhk;
  $item['category'] = !empty($item['category']) ? $item['category'] : 'Flat / Apartment';
  $item['furnishing'] = !empty($item['furnishing']) ? $item['furnishing'] : 'Semi-Furnished';

  $prefTenant = !empty($item['preferred_tenant']) ? $item['preferred_tenant'] : (!empty($item['tenant_preference']) ? $item['tenant_preference'] : 'All Welcome');
  $item['preferred_tenant'] = $prefTenant;
  $item['tenant_preference'] = $prefTenant;

  $food = !empty($item['food_rule']) ? $item['food_rule'] : (!empty($item['food_policy']) ? $item['food_policy'] : 'Non-Veg Allowed');
  $item['food_rule'] = $food;
  $item['food_policy'] = (str_contains(strtolower($food), 'veg') && !str_contains(strtolower($food), 'non')) ? 'pure_veg' : 'non_veg';
  $item['food_label'] = $food;

  $curfew = !empty($item['curfew_rule']) ? $item['curfew_rule'] : (!empty($item['gate_curfew']) ? $item['gate_curfew'] : 'No Curfew');
  $item['curfew_rule'] = $curfew;
  $item['gate_curfew'] = str_contains(strtolower($curfew), 'no') ? 'no_curfew' : 'has_curfew';
  $item['curfew_label'] = $curfew;

  $item['brokerage_type'] = !empty($item['brokerage_type']) ? $item['brokerage_type'] : 'zero_brokerage';
  $item['brokerage'] = !empty($item['brokerage']) ? $item['brokerage'] : 'Zero Brokerage';

  $item['trust_badge'] = !empty($item['trust_badge']) ? $item['trust_badge'] : (!empty($item['verified_badge']) ? 'POV Verified' : 'Title Checked');
  $item['freshness'] = !empty($item['freshness']) ? $item['freshness'] : 'Active • Checked recently';
  $item['rating'] = !empty($item['rating']) ? (string)$item['rating'] : '4.9';
  $item['reviews_count'] = !empty($item['reviews_count']) ? (int)$item['reviews_count'] : 14;

  // Amenities
  $amenities = $item['amenities'] ?? null;
  if (empty($amenities)) {
    $item['amenities'] = ['24x7 Water Supply', 'Power Backup', 'Gated Security', 'High Speed Wifi'];
  } elseif (is_string($amenities)) {
    $decoded = json_decode($amenities, true);
    $item['amenities'] = is_array($decoded) && !empty($decoded) ? $decoded : ['24x7 Water Supply', 'Power Backup', 'Gated Security'];
  } elseif (!is_array($amenities)) {
    $item['amenities'] = ['24x7 Water Supply', 'Power Backup', 'Gated Security'];
  }

  // Gallery
  $gallery = $item['gallery'] ?? null;
  if (empty($gallery)) {
    $item['gallery'] = [$img, 'realestate_03.webp', 'hotel_01.jpg'];
  } elseif (is_string($gallery)) {
    $decoded = json_decode($gallery, true);
    $item['gallery'] = is_array($decoded) && !empty($decoded) ? $decoded : [$img];
  } elseif (!is_array($gallery)) {
    $item['gallery'] = [$img];
  }

  return $item;
}

/**
 * Filter POV Indian Rentals by intent, city, landmark, budget, lifestyle rules, and search query
 */
function pov_get_rentals(?string $intent = null, ?string $city = null, ?string $landmark = null, ?string $budget = null, ?string $q = null, ?string $food = null, ?string $bachelor = null, ?string $curfew = null, ?string $power = null, ?string $brokerage = null): array {
  global $POV_RENTAL_LISTINGS;
  $list = $POV_RENTAL_LISTINGS;

  // Seamlessly integrate live MySQL database via Node.js API
  if (function_exists('node_rentals_search')) {
    $live = node_rentals_search();
    if (!empty($live) && is_array($live)) {
      $list = $live;
    }
  }

  $list = array_map('pov_normalize_rental_item', $list);

  if ($intent && $intent !== 'all') {
    $list = array_filter($list, fn($r) => ($r['rental_type'] ?? '') === $intent);
  }

  if ($city && $city !== 'all') {
    $c = strtolower(trim($city));
    $list = array_filter($list, fn($r) => str_contains(strtolower((string)($r['city'] ?? '')), $c));
  }

  if ($landmark && trim($landmark) !== '') {
    $lm = strtolower(trim($landmark));
    $clean_lm = trim(preg_replace('/^near\s+/i', '', $lm));
    $list = array_filter($list, function($r) use ($lm, $clean_lm) {
      $text = strtolower(($r['landmark'] ?? '') . ' ' . ($r['locality'] ?? '') . ' ' . ($r['title'] ?? '') . ' ' . ($r['city'] ?? '') . ' ' . ($r['desc'] ?? ''));
      if (str_contains($text, $lm)) return true;
      if ($clean_lm !== '' && str_contains($text, $clean_lm)) return true;
      $words = array_filter(explode(' ', $clean_lm), fn($w) => strlen(trim($w)) >= 3 && !in_array(trim($w), ['near', 'the', 'and', 'for', 'with', 'from']));
      foreach ($words as $w) {
        if (str_contains($text, trim($w))) return true;
      }
      return false;
    });
  }

  if ($budget && $budget !== 'all') {
    if ($budget === 'under-10k') {
      $list = array_filter($list, fn($r) => ($r['price_num'] ?? 0) <= 10000);
    } elseif ($budget === '10k-20k') {
      $list = array_filter($list, fn($r) => ($r['price_num'] ?? 0) > 10000 && ($r['price_num'] ?? 0) <= 20000);
    } elseif ($budget === '20k-40k') {
      $list = array_filter($list, fn($r) => ($r['price_num'] ?? 0) > 20000 && ($r['price_num'] ?? 0) <= 40000);
    } elseif ($budget === 'above-40k') {
      $list = array_filter($list, fn($r) => ($r['price_num'] ?? 0) > 40000);
    }
  }

  if ($food && $food !== 'all') {
    if ($food === 'pure_veg') {
      $list = array_filter($list, fn($r) => ($r['food_policy'] ?? '') === 'pure_veg' || ($r['food_policy'] ?? '') === 'jain_friendly');
    } elseif ($food === 'jain') {
      $list = array_filter($list, fn($r) => ($r['food_policy'] ?? '') === 'jain_friendly');
    } elseif ($food === 'non_veg') {
      $list = array_filter($list, fn($r) => ($r['food_policy'] ?? '') === 'non_veg' || ($r['food_policy'] ?? '') === 'no_restriction');
    }
  }

  if ($bachelor && $bachelor !== 'all') {
    if ($bachelor === 'bachelors') {
      $list = array_filter($list, fn($r) => in_array($r['bachelor_policy'] ?? '', ['bachelor_friendly', 'female_only', 'male_only', 'all_welcome']));
    } elseif ($bachelor === 'family') {
      $list = array_filter($list, fn($r) => ($r['bachelor_policy'] ?? '') === 'family_preferred' || ($r['bachelor_policy'] ?? '') === 'all_welcome');
    } elseif ($bachelor === 'girls') {
      $list = array_filter($list, fn($r) => ($r['bachelor_policy'] ?? '') === 'female_only' || ($r['bachelor_policy'] ?? '') === 'all_welcome');
    } elseif ($bachelor === 'boys') {
      $list = array_filter($list, fn($r) => ($r['bachelor_policy'] ?? '') === 'male_only' || ($r['bachelor_policy'] ?? '') === 'bachelor_friendly' || ($r['bachelor_policy'] ?? '') === 'all_welcome');
    }
  }

  if ($curfew && $curfew !== 'all') {
    if ($curfew === 'no_curfew') {
      $list = array_filter($list, fn($r) => ($r['gate_curfew'] ?? '') === 'no_curfew');
    } elseif ($curfew === 'has_curfew') {
      $list = array_filter($list, fn($r) => ($r['gate_curfew'] ?? '') === 'has_curfew');
    }
  }

  if ($power && $power !== 'all') {
    $list = array_filter($list, fn($r) => ($r['electricity_type'] ?? '') === $power);
  }

  if ($brokerage && $brokerage !== 'all') {
    if ($brokerage === 'zero_brokerage') {
      $list = array_filter($list, fn($r) => ($r['brokerage_type'] ?? '') === 'zero_brokerage');
    }
  }

  if ($q && trim($q) !== '') {
    $query = strtolower(trim($q));
    $list = array_filter($list, function($r) use ($query) {
      $haystack = strtolower(($r['title'] ?? '') . ' ' . ($r['city'] ?? '') . ' ' . ($r['landmark'] ?? '') . ' ' . ($r['locality'] ?? '') . ' ' . ($r['category'] ?? '') . ' ' . ($r['furnishing'] ?? '') . ' ' . ($r['food_label'] ?? '') . ' ' . ($r['curfew_label'] ?? '') . ' ' . ($r['electricity_rate'] ?? ''));
      return str_contains($haystack, $query);
    });
  }

  return array_values($list);
}

function pov_find_rental(int $id): ?array {
  // Check live API/MySQL first
  if (function_exists('node_rentals_get')) {
    $item = node_rentals_get($id);
    if (!empty($item) && is_array($item)) {
      return pov_normalize_rental_item($item);
    }
  }

  global $POV_RENTAL_LISTINGS;
  foreach ($POV_RENTAL_LISTINGS as $r) {
    if ((int)$r['id'] === $id) return pov_normalize_rental_item($r);
  }
  return null;
}

